export function createTranslator(lang: Language) {
  const dict = (lang && translations[lang]) ? translations[lang] : translations.es;
  return (key: TranslationKey): string => (dict && (dict as any)[key]) ?? (translations.es as Record<string, string>)[key] ?? key;
}
